"""법 조문이 필요한 주행 엣지 케이스의 목록과 발동 판정, 조문 문장 나누기를 담은 모듈"""

ACTIONS = ["정지", "양보", "서행", "진입·회전 금지", "앞지르기·차로 변경 금지", "주의"]

# 엣지 케이스마다 함께 있어야 하는 사실
# 차도 보행자는 보행자가 차도 위에 있는지 판단할 인식 수단이 아직 없어 어떤 인식 경로도 만들지 않는 사실을 요구함
EDGE_CASES = {
    "적색 신호 교차로": {"적색 신호"},
    "황색 신호": {"황색 신호"},
    "횡단보도 보행자": {"보행자", "횡단보도"},
    "차도 보행자": {"차도 위 보행자"},
    "정지 표지": {"정지 표지"},
    "양보 표지": {"양보 표지"},
    "회전 금지 표지": {"회전 금지 표지"},
    "버스 전용차로": {"버스 전용 글자가 쓰인 차로"},
    "노면전차 선로": {"노면전차 선로"},
    "터널": {"터널"},
    "공사 구간": {"라바콘"},
    "자전거 근접": {"자전거"},
    "통학버스": {"통학버스"},
    "긴급자동차": {"긴급자동차"},
    "철길 건널목": {"철길 건널목"},
    "회전교차로": {"회전교차로"},
    "어린이보호구역": {"어린이보호구역"},
}


def active_edge_cases(facts):
    """사실 집합에서 발동 조건을 만족하는 엣지 케이스 이름 목록을 만드는 함수"""
    return [name for name, needs in EDGE_CASES.items() if needs <= facts]


def sentences(text):
    """조문을 문장 목록으로 나누는 함수"""
    # 한국 조문은 "1. 교차로 2. 터널 안"처럼 호 번호에도 마침표가 있어 문장 끝인 "다. "에서만 나눔
    # 영어 조문에는 "다"가 없고 한국 조문은 모두 "-다"로 끝나는 문장을 가짐
    if "다" in text:
        parts, ending = text.split("다. "), "다."
    else:
        parts, ending = text.split(". "), "."
    # 나눌 때 잘려 나간 문장 끝을 마지막 조각을 뺀 나머지에 다시 붙임
    return [part + ending for part in parts[:-1]] + parts[-1:]
